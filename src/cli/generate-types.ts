/**
 * `envshield generate-types` — generates a TypeScript declaration file that augments
 * `NodeJS.ProcessEnv` with typed entries for the specified environment variables.
 *
 * Usage: envshield generate-types VAR1 VAR2 ... > env.d.ts
 *
 * This gives IDE autocomplete and type safety for `process.env.DATABASE_URL` etc.
 */

export interface GenerateTypesOptions {
  /** Variable names to include in the generated declarations. */
  vars: string[];
  /** Variables that are secrets (will be typed as `never` after freeze). */
  secretVars?: string[];
}

export interface GenerateTypesResult {
  code: 0 | 1;
  output: string[];
  /** The generated TypeScript declaration content. */
  content: string;
}

export function runGenerateTypes(options: GenerateTypesOptions): GenerateTypesResult {
  const { vars, secretVars = [] } = options;

  if (vars.length === 0) {
    return {
      code: 1,
      output: ['Error: no variable names provided.\nUsage: envshield generate-types VAR1 VAR2 ...'],
      content: '',
    };
  }

  const secretSet = new Set(secretVars);
  const lines: string[] = [
    '// Generated by envshield generate-types',
    '// Do not edit manually — re-run to regenerate.',
    '',
    'declare global {',
    '  namespace NodeJS {',
    '    interface ProcessEnv {',
  ];

  for (const varName of vars) {
    if (secretSet.has(varName)) {
      // Secrets are removed from process.env after freeze(), so type as `never` post-freeze
      // For pre-freeze access, type as string | undefined (normal env var)
      lines.push(
        '      /** @envshield secret — removed from process.env after envshield.freeze() */',
      );
      lines.push(`      readonly ${varName}?: string;`);
    } else {
      lines.push(`      readonly ${varName}?: string;`);
    }
  }

  lines.push('    }');
  lines.push('  }');
  lines.push('}');
  lines.push('');
  lines.push('export {};');
  lines.push('');

  const content = lines.join('\n');
  return { code: 0, output: [content], content };
}
